CREATE TABLE IF NOT EXISTS "EmployeeRegistrationRequest" (
  "requestId" uuid PRIMARY KEY, "employeeId" text NOT NULL REFERENCES "Employee"(id),
  "actorId" uuid NOT NULL REFERENCES "HRUser"(id), "payloadHash" text NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION aa_employee_receipt_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Employee registration receipts are immutable'; END $$;
DROP TRIGGER IF EXISTS employee_registration_request_immutable ON "EmployeeRegistrationRequest";
CREATE TRIGGER employee_registration_request_immutable BEFORE UPDATE OR DELETE ON "EmployeeRegistrationRequest" FOR EACH ROW EXECUTE FUNCTION aa_employee_receipt_immutable();
COMMIT;
