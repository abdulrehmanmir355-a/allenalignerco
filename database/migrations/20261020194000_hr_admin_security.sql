CREATE TABLE IF NOT EXISTS "HRUser" (
  "id" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  "email" VARCHAR(254) NOT NULL UNIQUE,
  "passwordHash" TEXT NOT NULL,
  "role" VARCHAR(20) NOT NULL DEFAULT 'HR_OFFICER'
    CHECK ("role" IN ('HR_ADMIN','HR_OFFICER','HR_VIEWER')),
  "isActive" BOOLEAN NOT NULL DEFAULT TRUE,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS "HRSession" (
  "tokenHash" TEXT PRIMARY KEY,
  "hrUserId" UUID NOT NULL
    REFERENCES "HRUser"("id") ON DELETE CASCADE,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS "HRSession_expires_idx"
ON "HRSession" ("expiresAt");
